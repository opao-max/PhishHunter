"""Deterministic offline LLM used by demos, tests and CI.

``MockLLM`` is not a classifier: it is a *contract-compliant stub* that proves
the orchestration works without a network.  For the analyst prompt it builds a
valid analyst JSON object strictly from the evidence digest supplied by
``LLMAnalyst``; it never invents an IOC and never cites an ID that is absent
from the digest.

Markers recognised (both are generated by the core modules):

* ``PLAN_DIGEST_JSON:``      -> ``{"calls": []}`` (planner falls back to policy)
* ``EVIDENCE_DIGEST_JSON:``  -> analyst schema grounded in the digest
"""

from __future__ import annotations

import json
import time
from typing import Any

from .base import LLMProvider, LLMResponse

PLAN_MARKER = "PLAN_DIGEST_JSON:"
EVIDENCE_MARKER = "EVIDENCE_DIGEST_JSON:"

INJECTION_TAGS = {
    "instruction_override",
    "hidden_content",
    "verdict_steering",
    "fake_tool_result",
    "role_manipulation",
}


def _as_float(value: Any, default: float | None = None) -> float | None:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _extract_digest(prompt: str, marker: str) -> dict[str, Any]:
    """Decode the first JSON object following ``marker``.

    Using ``raw_decode`` avoids the classic "first brace to last brace" bug
    when the prompt appends prose or an ``<untrusted_email_content>`` block.
    """
    index = prompt.find(marker)
    if index < 0:
        return {}
    start = prompt.find("{", index + len(marker))
    if start < 0:
        return {}
    try:
        value, _ = json.JSONDecoder().raw_decode(prompt[start:])
    except json.JSONDecodeError:
        return {}
    return value if isinstance(value, dict) else {}


def _evidence_weight(item: dict[str, Any]) -> float:
    severity = _as_float(item.get("severity"), 0.0) or 0.0
    confidence = _as_float(item.get("confidence"), 0.0) or 0.0
    return max(0.0, min(1.0, severity)) * max(0.0, min(1.0, confidence))


def _digest_injection(digest: dict[str, Any]) -> bool:
    if bool(digest.get("injection_suspected")):
        return True
    for item in digest.get("evidence") or []:
        if not isinstance(item, dict):
            continue
        tags = item.get("tags") or []
        if (
            item.get("polarity") != "mitigating"
            and (
                str(item.get("category") or "") == "prompt_injection"
                or (isinstance(tags, list) and INJECTION_TAGS & {str(tag) for tag in tags})
            )
        ):
            return True
    return False


def _select_citations(items: list[dict[str, Any]]) -> tuple[list[str], list[dict[str, Any]]]:
    """Return the top 2-4 cited IDs and the matching evidence items."""
    ranked = sorted(
        items,
        key=lambda item: (
            item.get("polarity") == "mitigating",
            -_evidence_weight(item),
            str(item.get("id")),
        ),
    )
    risk = [item for item in ranked if item.get("polarity") != "mitigating"]
    pool = list(risk) or list(ranked)
    # Prefer risk evidence, but top up with mitigating facts rather than
    # claiming a score from a single citation.
    if len(pool) < 2:
        for item in ranked:
            if item not in pool:
                pool.append(item)

    cited: list[str] = []
    for item in pool:
        evidence_id = str(item.get("id") or "").strip()
        if evidence_id and evidence_id not in cited:
            cited.append(evidence_id)
        if len(cited) >= 4:
            break
    # A tiny corpus may only contain one citable item; never fabricate more.
    return cited, pool


def _build_analyst_payload(digest: dict[str, Any]) -> dict[str, Any]:
    items = [
        item
        for item in (digest.get("evidence") or [])
        if isinstance(item, dict) and str(item.get("id") or "").strip()
    ]
    cited, pool = _select_citations(items)
    by_id = {str(item.get("id")).strip(): item for item in items}

    deterministic = _as_float(digest.get("deterministic_score"))
    suggested: float | None = None
    if deterministic is not None and len(cited) >= 2:
        # Stay inside the +/-5 band the contract allows; exact agreement is
        # the most honest offline behaviour.
        suggested = round(max(0.0, min(100.0, deterministic)), 1)

    reasoning: list[str] = []
    for evidence_id in cited:
        item = by_id[evidence_id]
        title = str(item.get("title") or "证据").strip()
        detail = str(item.get("detail") or "").strip()
        if len(detail) > 140:
            detail = detail[:137] + "..."
        reasoning.append(f"[{evidence_id}] {title}：{detail}" if detail else f"[{evidence_id}] {title}")
    if suggested is not None and cited:
        reasoning.append(
            f"[{cited[0]}] 离线模型核对证据链后，建议评分与确定性评分 "
            f"{deterministic:.1f} 保持一致。"
        )

    if not cited:
        summary = "未发现可引用的证据，无法形成可靠结论，建议人工复核。"
    elif suggested is not None:
        lead = str(pool[0].get("title") or "多项可疑信号").strip()
        summary = (
            f"确定性证据评分 {suggested:.0f}/100；主要依据为「{lead}」等 "
            f"{len(cited)} 条证据。处置建议按评分阈值执行。"
        )
    else:
        summary = "有效证据不足两条，仅提供有限判断，建议人工复核。"

    return {
        "summary": summary,
        "reasoning_steps": reasoning,
        "cited_evidence_ids": cited,
        "suggested_score": suggested,
        "confidence": 0.82 if suggested is not None else 0.55,
        "conflicts": [],
        "injection_suspected": _digest_injection(digest),
    }


_EMPTY_ANALYST: dict[str, Any] = {
    "summary": "未提供可分析的内容。",
    "reasoning_steps": [],
    "cited_evidence_ids": [],
    "suggested_score": None,
    "confidence": 0.5,
    "conflicts": [],
    "injection_suspected": False,
}


class MockLLM(LLMProvider):
    """Offline, deterministic provider with no external dependencies."""

    name = "mock"
    model = "offline-deterministic"

    def generate(
        self,
        system: str,
        prompt: str,
        *,
        json_mode: bool = False,
        temperature: float = 0.1,
        max_tokens: int = 1400,
    ) -> LLMResponse:
        started = time.perf_counter()

        if EVIDENCE_MARKER in prompt:
            payload = _build_analyst_payload(_extract_digest(prompt, EVIDENCE_MARKER))
        elif PLAN_MARKER in prompt:
            payload = {"calls": []}
        else:
            payload = dict(_EMPTY_ANALYST)

        text = json.dumps(payload, ensure_ascii=False)
        return LLMResponse(
            text=text,
            provider=self.name,
            model=self.model,
            latency_ms=round((time.perf_counter() - started) * 1000, 3),
            usage={
                "prompt_chars": len(system or "") + len(prompt or ""),
                "completion_chars": len(text),
            },
        )